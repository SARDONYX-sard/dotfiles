//! Per-shell syntax. All quoting lives here.

use std::fmt::Write as _;

use schemars::JsonSchema;
use serde::Deserialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum Shell {
    Bash,
    Fish,
    Pwsh,
    Nu,
}

impl std::str::FromStr for Shell {
    type Err = String;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "bash" => Ok(Self::Bash),
            "fish" => Ok(Self::Fish),
            "pwsh" | "powershell" => Ok(Self::Pwsh),
            "nu" | "nushell" => Ok(Self::Nu),
            _ => Err(format!("unknown shell `{s}` (bash, fish, pwsh, nu)")),
        }
    }
}

impl Shell {
    pub const fn ext(self) -> &'static str {
        match self {
            Self::Bash => "bash",
            Self::Fish => "fish",
            Self::Pwsh => "ps1",
            Self::Nu => "nu",
        }
    }

    pub const fn name(self) -> &'static str {
        match self {
            Self::Bash => "bash",
            Self::Fish => "fish",
            Self::Pwsh => "pwsh",
            Self::Nu => "nu",
        }
    }
}

pub struct Emitter {
    shell: Shell,
    buf: String,
    /// pwsh `using` statements must precede every other statement in a script.
    usings: Vec<String>,
}

impl Emitter {
    pub fn new(shell: Shell) -> Self {
        Self {
            shell,
            buf: String::new(),
            usings: Vec::new(),
        }
    }

    pub fn header(&mut self) {
        self.line("# Generated by `dot gen`. Do not edit; edit shell/shared.toml in dots/core or your profile.");
    }

    pub fn env(&mut self, vars: &[(&str, &str)]) {
        if vars.is_empty() {
            return;
        }
        self.section("env");
        for (k, v) in vars {
            let line = match self.shell {
                Shell::Bash => format!("export {k}={}", sh_quote(v)),
                Shell::Fish => format!("set -gx {k} {}", fish_quote(v)),
                Shell::Pwsh => format!("$env:{k} = {}", ps_quote(v)),
                Shell::Nu => format!("$env.{k} = {}", nu_quote(v)),
            };
            self.line(&line);
        }
    }

    pub fn path_prepend(&mut self, dirs: &[String]) {
        if dirs.is_empty() {
            return;
        }
        self.section("path");
        match self.shell {
            Shell::Bash => {
                for d in dirs.iter().rev() {
                    let q = sh_quote(d);
                    self.line(&format!(
                        "case \":$PATH:\" in *:{q}:*) ;; *) PATH={q}:\"$PATH\" ;; esac"
                    ));
                }
                self.line("export PATH");
            }
            Shell::Fish => {
                let list = dirs
                    .iter()
                    .map(|d| fish_quote(d))
                    .collect::<Vec<_>>()
                    .join(" ");
                self.line(&format!("fish_add_path -gP {list}"));
            }
            Shell::Pwsh => {
                // No cmdlets from Microsoft.PowerShell.Utility/Management here: their
                // first use auto-loads the module (~350ms on startup).
                let list = dirs
                    .iter()
                    .map(|d| ps_quote(d))
                    .collect::<Vec<_>>()
                    .join(", ");
                // Child scope `& {}` keeps `$seen` local (no Remove-Variable needed).
                self.line(&format!(
                    "& {{ $seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase); $env:PATH = (@({list}) + ($env:PATH -split [IO.Path]::PathSeparator)).Where({{ $_ -and $seen.Add($_) }}) -join [IO.Path]::PathSeparator }}"
                ));
            }
            Shell::Nu => {
                let list = dirs
                    .iter()
                    .map(|d| nu_quote(d))
                    .collect::<Vec<_>>()
                    .join(" ");
                self.line(&format!(
                    "$env.PATH = ($env.PATH | prepend [{list}] | uniq)"
                ));
            }
        }
    }

    pub fn aliases(&mut self, aliases: &[(&str, &str)]) {
        if aliases.is_empty() {
            return;
        }
        self.section("alias");
        if self.shell == Shell::Pwsh {
            // Built-in aliases (gc, gl, gp, ls, cat, ...) win over functions; drop them first.
            let names = aliases
                .iter()
                .map(|(n, _)| ps_quote(n))
                .collect::<Vec<_>>()
                .join(", ");
            // Provider API instead of Get-Alias/Remove-Item (module auto-load cost).
            self.line(&format!(
                "foreach ($n in @({names})) {{ $p = \"Alias:\\$n\"; if ($ExecutionContext.InvokeProvider.Item.Exists($p, $true, $true)) {{ $ExecutionContext.InvokeProvider.Item.Remove(@($p), $false, $true, $true) }} }}"
            ));
        }
        for (name, cmd) in aliases {
            let (head, rest) = cmd.split_once(' ').unwrap_or((cmd, ""));
            let recursive = head == *name;
            let text = match self.shell {
                Shell::Bash => format!("alias {name}={}", sh_quote(cmd)),
                Shell::Fish => {
                    let call = if recursive {
                        format!("command {cmd}")
                    } else {
                        cmd.to_string()
                    };
                    format!(
                        "function {name} --wraps {}\n    {call} $argv\nend",
                        fish_quote(head)
                    )
                }
                Shell::Pwsh => {
                    let call = if recursive {
                        format!(
                            "& (Get-Command {} -CommandType Application)[0] {rest}",
                            ps_quote(head)
                        )
                    } else {
                        cmd.to_string()
                    };
                    format!("function {name} {{ {} @args }}", call.trim_end())
                }
                Shell::Nu => format!("alias {name} = {cmd}"),
            };
            self.line(&text);
        }
    }

    pub fn raw(&mut self, title: &str, text: &str) {
        self.buf.push('\n');
        self.line(title);
        for l in text.trim_end().lines() {
            let is_using = l.trim_start().to_ascii_lowercase().starts_with("using ");
            if self.shell == Shell::Pwsh && is_using {
                let u = l.trim().to_string();
                if !self.usings.contains(&u) {
                    self.usings.push(u);
                }
            } else {
                self.line(l);
            }
        }
    }

    pub fn finish(self) -> String {
        if self.usings.is_empty() {
            return self.buf;
        }
        // Header comment first, then the hoisted `using`s.
        let (head, rest) = self.buf.split_once('\n').unwrap_or((&self.buf, ""));
        format!("{head}\n{}\n{rest}", self.usings.join("\n"))
    }

    fn section(&mut self, name: &str) {
        let _ = write!(self.buf, "\n# --- {name}\n");
    }

    fn line(&mut self, s: &str) {
        self.buf.push_str(s);
        self.buf.push('\n');
    }
}

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

fn fish_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', r"\\").replace('\'', r"\'"))
}

fn ps_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

fn nu_quote(s: &str) -> String {
    // Raw string: no escaping needed unless the value contains `'#`.
    format!("r#'{s}'#")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(sh_quote("it's"), r"'it'\''s'");
        assert_eq!(fish_quote(r"a\b'c"), r"'a\\b\'c'");
        assert_eq!(ps_quote("it's"), "'it''s'");
        assert_eq!(nu_quote("a'b"), "r#'a'b'#");
    }
}
